/**
 * Calibrate the context-faithfulness judge against 20 human-labelled answers.
 *
 * 1. Resolve each labelled answer's contextChunkIds to chunk text from the corpus.
 * 2. Write evals/calibration/tests.generated.yaml and run promptfoo over it (echo provider).
 * 3. Read the raw faithfulness scores, sweep thresholds, print agreement and Cohen's kappa
 *    per threshold, and write results/calibration-summary.json.
 *
 *   bun scripts/calibrate-judge.ts [--skip-eval] [--judge openrouter:anthropic/claude-sonnet-5]
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { parse as parseYaml, stringify as toYaml } from "yaml";
import { loadCorpus } from "../src/retrieval/chunk.js";

interface Labelled {
  id: string;
  query: string;
  contextChunkIds: string[];
  answer: string;
  faithful: boolean;
  note?: string;
}

interface PromptfooResultRow {
  vars?: Record<string, unknown>;
  testCase?: { vars?: Record<string, unknown>; metadata?: Record<string, unknown> };
  gradingResult?: { score?: number; componentResults?: Array<{ score?: number; reason?: string }> };
  score?: number;
}

const { values: args } = parseArgs({
  options: {
    "skip-eval": { type: "boolean", default: false },
    labels: { type: "string", default: "evals/calibration/labelled-answers.yaml" },
    out: { type: "string", default: "results/calibration.json" },
  },
});

const labelsPath = args.labels ?? "evals/calibration/labelled-answers.yaml";
const outPath = args.out ?? "results/calibration.json";
const generatedPath = "evals/calibration/tests.generated.yaml";

const chunks = new Map(loadCorpus("corpus").map((c) => [c.id, c] as const));
const labelled = parseYaml(readFileSync(labelsPath, "utf8")) as Labelled[];

const tests = labelled.map((l) => {
  const context = l.contextChunkIds.map((id) => {
    const chunk = chunks.get(id);
    if (!chunk) throw new Error(`${l.id}: unknown chunk id ${id}`);
    return `${chunk.title} / ${chunk.heading}\n${chunk.text}`;
  });
  return {
    description: `${l.id} (${l.faithful ? "faithful" : "unfaithful"})`,
    vars: { query: l.query, answer: l.answer, context: context.join("\n\n") },
    metadata: { id: l.id, faithful: l.faithful, note: l.note ?? "" },
  };
});
writeFileSync(generatedPath, `# Generated by scripts/calibrate-judge.ts. Do not edit.\n${toYaml(tests)}`);
console.log(`Wrote ${generatedPath} (${tests.length} rows)`);

if (!args["skip-eval"]) {
  const cmd = process.platform === "win32" ? "npx.cmd" : "npx";
  const run = spawnSync(
    cmd,
    ["promptfoo", "eval", "--env-file", ".env", "-c", "promptfooconfig.calibration.yaml", "--no-cache", "-o", outPath],
    { stdio: "inherit", shell: process.platform === "win32" },
  );
  // promptfoo exits 100 when assertions fail; threshold 0 means that should not happen, but tolerate it.
  if (run.status !== 0 && run.status !== 100) {
    console.error(`promptfoo exited with ${run.status}`);
    process.exit(1);
  }
}

if (!existsSync(outPath)) {
  console.error(`${outPath} not found; run without --skip-eval first.`);
  process.exit(1);
}

const raw = JSON.parse(readFileSync(outPath, "utf8")) as { results?: { results?: PromptfooResultRow[] } | PromptfooResultRow[] };
const rows: PromptfooResultRow[] = Array.isArray(raw.results) ? raw.results : (raw.results?.results ?? []);

const scored = rows.map((r) => {
  const id = String(r.testCase?.metadata?.id ?? r.vars?.id ?? "");
  const label = labelled.find((l) => l.id === id);
  const score = r.gradingResult?.componentResults?.[0]?.score ?? r.gradingResult?.score ?? r.score ?? 0;
  const reason = r.gradingResult?.componentResults?.[0]?.reason ?? "";
  return { id, human: label?.faithful ?? null, score, reason };
}).filter((s) => s.human !== null) as Array<{ id: string; human: boolean; score: number; reason: string }>;

if (scored.length === 0) {
  console.error("No scored rows matched the labelled ids; check the results file shape.");
  process.exit(1);
}

function kappa(pairs: Array<[boolean, boolean]>): number {
  const n = pairs.length;
  let tp = 0, tn = 0, fp = 0, fn = 0;
  for (const [human, judge] of pairs) {
    if (human && judge) tp++;
    else if (!human && !judge) tn++;
    else if (!human && judge) fp++;
    else fn++;
  }
  const po = (tp + tn) / n;
  const pYes = ((tp + fp) / n) * ((tp + fn) / n);
  const pNo = ((tn + fn) / n) * ((tn + fp) / n);
  const pe = pYes + pNo;
  return pe === 1 ? 1 : (po - pe) / (1 - pe);
}

const thresholds = [0.5, 0.6, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95, 1.0];
console.log("\n| threshold | agreement | kappa | false accepts | false rejects |");
console.log("|---|---|---|---|---|");
const sweep = thresholds.map((t) => {
  const pairs = scored.map((s): [boolean, boolean] => [s.human, s.score >= t]);
  const agree = pairs.filter(([h, j]) => h === j).length / pairs.length;
  const falseAccepts = pairs.filter(([h, j]) => !h && j).length;
  const falseRejects = pairs.filter(([h, j]) => h && !j).length;
  const k = kappa(pairs);
  console.log(`| ${t.toFixed(2)} | ${agree.toFixed(2)} | ${k.toFixed(2)} | ${falseAccepts} | ${falseRejects} |`);
  return { threshold: t, agreement: agree, kappa: k, falseAccepts, falseRejects };
});

const best = [...sweep].sort((a, b) => b.kappa - a.kappa || b.agreement - a.agreement)[0]!;
console.log(`\nBest threshold by kappa: ${best.threshold} (agreement ${best.agreement.toFixed(2)}, kappa ${best.kappa.toFixed(2)})`);
console.log("\nPer-row scores:");
for (const s of scored) console.log(`  ${s.id}  human=${s.human ? "faithful" : "unfaithful"}  judge=${s.score.toFixed(2)}`);

mkdirSync("results", { recursive: true });
writeFileSync(
  "results/calibration-summary.json",
  JSON.stringify({ generatedAt: new Date().toISOString(), n: scored.length, sweep, best, rows: scored }, null, 2),
);
console.log("\nWrote results/calibration-summary.json");
